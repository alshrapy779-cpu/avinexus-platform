import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const source=readFileSync(new URL('../../src/modules/v20/PartnerOfficeCustomerNetworkR7.ts',import.meta.url),'utf8');
const moduleUrl='data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(source)).toString('base64');
const m=await import(moduleUrl);
const original=m.buildPartnerOfficeCustomerNetworkR7();
const old=JSON.stringify(original);
const renamed=m.renameOfficeR7(original,'r7-off-sanaa','مكتب صنعاء الجديد');
assert.equal(renamed.offices.find(o=>o.id==='r7-off-sanaa').name,'مكتب صنعاء الجديد');
assert.equal(original.offices.find(o=>o.id==='r7-off-sanaa').name,'مكتب صنعاء لإدارة المزارع');
assert.deepEqual(renamed.customers,original.customers);
assert.throws(()=>m.renameOfficeR7(original,'missing','x'),/office_not_found/);
const withRegion=m.addGovernorateR7(original,'محافظة اختبار');
assert.equal(withRegion.governorates.length,original.governorates.length+1);
assert.throws(()=>m.addGovernorateR7(original,'صنعاء'),/governorate_already_exists/);
const org=original.organizations[0];
const input={code:'MKT-TEST',name:'شركة تسويق اختبار',contact_name:'اختبار',phone:'123',governorates_served:[],payment_terms:'',credit_days:0,preferred_currency:'SAR',status:'active'};
const marketed=m.registerMarketingCompanyR7(original,input);
assert.equal(marketed.organizations.at(-1).kind,'marketing_company');
assert.equal(marketed.offices.length,original.offices.length);
assert.equal(m.classifyR7Party('marketing_company'),'marketing_company');
assert.throws(()=>m.registerMarketingCompanyR7(marketed,input),/company_code_conflict/);
assert.equal(JSON.stringify(original),old);
console.log('PASS 9 identity, isolation and immutability assertions');
