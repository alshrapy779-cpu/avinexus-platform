import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../..');
const baseline=JSON.parse(fs.readFileSync(path.join(root,'docs/v20.2/PRESERVATION_BASELINE_V20_1.json'),'utf8'));
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const missing=Object.keys(baseline.files).filter(rel=>!fs.existsSync(path.join(root,rel)));
const server=fs.readFileSync(path.join(root,'server.ts'),'utf8');
const currentRoutes=[...server.matchAll(/app\.(?:get|post|put|patch|delete)\(\s*['"]([^'"]+)/g)].map(m=>m[1]);
const missingRoutes=baseline.routes.filter(r=>!currentRoutes.includes(r));
const exportRegex=/^export\s+(?:default\s+)?(?:async\s+)?(?:const|let|var|function|class|interface|type|enum)\s+([A-Za-z0-9_]+)/gm;
const currentExports=[];
const walk=d=>{for(const e of fs.readdirSync(d,{withFileTypes:true})){const p=path.join(d,e.name);if(e.isDirectory())walk(p);else if(/\.tsx?$/.test(e.name)){const txt=fs.readFileSync(p,'utf8');for(const m of txt.matchAll(exportRegex))currentExports.push(`${path.relative(root,p).replaceAll('\\','/')}::${m[1]}`)}}};
walk(path.join(root,'src'));
const missingExports=baseline.exports.filter(e=>!currentExports.includes(e));
const result={baseline:'V20.1',baseline_files:Object.keys(baseline.files).length,missing_files:missing,missing_routes:missingRoutes,missing_exports:missingExports,passed:missing.length===0&&missingRoutes.length===0&&missingExports.length===0,checked_at:new Date().toISOString()};
console.log(JSON.stringify(result,null,2));
if(!result.passed) process.exit(1);
